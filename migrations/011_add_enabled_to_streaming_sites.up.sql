-- 011_add_enabled_to_streaming_sites.up.sql
-- Тоглы вкл/выкл для каждого сайта в персональном списке — пользователь может временно
-- отключить сайт (например, если он перестал работать), не удаляя его из списка навсегда.
-- Отключённые сайты не показываются в дропдауне «Где смотреть» при добавлении дорамы,
-- но остаются на странице настроек, чтобы их можно было включить обратно.
-- DEFAULT true — все существующие и новые сайты (включая дефолтные 10 у новых пользователей)
-- включены по умолчанию.

ALTER TABLE streaming_sites
    ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN streaming_sites.enabled IS 'Показывать ли сайт в дропдауне «Где смотреть» — тогл на странице настроек, по умолчанию true';
